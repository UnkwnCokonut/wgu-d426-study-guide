"""Render the ready-made podcast episodes to MP3 with Piper (two voices: Alex and Sam).

Run from the repo root, after tools/build.py:

    pip install piper-tts playwright markdown
    python3 tools/podcast.py            # all ready-made episodes
    python3 tools/podcast.py c3 cram    # just some

It loads index.html in headless Chromium and asks the page for each episode's script
(window.D426_buildScript), so the audio and the on-screen transcript always match.

Writes audio/<episode>.mp3 and data/podcast.js (titles, durations, and a timed transcript).
Needs ffmpeg on PATH. Voices are downloaded once into tools/.voices/ (not committed).
"""
import hashlib
import io
import json
import subprocess
import sys
import tarfile
import urllib.request
import wave
from pathlib import Path

import numpy as np
from piper import PiperVoice, SynthesisConfig
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent.parent
VOICE_DIR = ROOT / "tools" / ".voices"
VOICES = {  # speaker -> Piper voice (from the rhasspy/piper GitHub releases)
    "A": "en-us-lessac-medium",  # Alex: explains
    "B": "en-us-ryan-medium",    # Sam: asks, quizzes, keeps it moving
}
READY = ["blueprint", "c3", "c2", "c1", "cram", "quiz-c3", "quiz-c2", "quiz-c1"]
THINK_MS = 3000
BITRATE = "40k"


def voice_path(name):
    onnx = VOICE_DIR / name / f"{name}.onnx"
    if not onnx.exists():
        url = f"https://github.com/rhasspy/piper/releases/download/v0.0.2/voice-{name}.tar.gz"
        print(f"downloading {url}")
        (VOICE_DIR / name).mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(url) as r:
            tarfile.open(fileobj=io.BytesIO(r.read()), mode="r:gz").extractall(VOICE_DIR / name)
    return onnx


def scripts(ids):
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        page.goto((ROOT / "index.html").as_uri())
        page.wait_for_function("() => !!window.D426_buildScript")
        out = {i: {"title": page.evaluate("id => D426_epTitle(id)", i),
                   "segs": page.evaluate("([id, t]) => D426_buildScript(id, t)", [i, THINK_MS])} for i in ids}
        browser.close()
    return out


def main():
    ids = sys.argv[1:] or READY
    voices = {spk: PiperVoice.load(str(voice_path(name))) for spk, name in VOICES.items()}
    rate = max(v.config.sample_rate for v in voices.values())  # resample everything to the highest rate

    def resample(x, src):
        if src == rate:
            return x
        n = int(round(len(x) * rate / src))
        return np.interp(np.linspace(0, len(x) - 1, n), np.arange(len(x)), x).astype(np.float32)
    cfg = SynthesisConfig(length_scale=1.0, normalize_audio=True)

    manifest_file = ROOT / "data" / "podcast.js"
    manifest = {"voices": {"A": "Alex (Piper lessac)", "B": "Sam (Piper ryan)"}, "episodes": {}}
    if manifest_file.exists():  # keep episodes we aren't re-rendering
        txt = manifest_file.read_text(encoding="utf-8")
        manifest = json.loads(txt[txt.index("{"): txt.rindex("}") + 1])

    (ROOT / "audio").mkdir(exist_ok=True)
    for ep_id, ep in scripts(ids).items():
        parts, n, segs = [], 0, []
        for s in ep["segs"]:
            segs.append({k: v for k, v in {"t": round(n / rate, 2), "spk": s["spk"], "text": s["text"], "mod": s.get("mod")}.items() if v is not None})
            for chunk in voices[s["spk"]].synthesize(s["say"], syn_config=cfg):
                x = resample(np.asarray(chunk.audio_float_array, dtype=np.float32), chunk.sample_rate)
                parts.append(x); n += len(x)
            gap = np.zeros(int(rate * s.get("pause", 400) / 1000), dtype=np.float32)
            parts.append(gap); n += len(gap)
        pcm = (np.clip(np.concatenate(parts), -1, 1) * 32767).astype("<i2")
        wav = io.BytesIO()
        with wave.open(wav, "wb") as w:
            w.setnchannels(1); w.setsampwidth(2); w.setframerate(rate); w.writeframes(pcm.tobytes())
        mp3 = ROOT / "audio" / f"{ep_id}.mp3"
        subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-f", "wav", "-i", "pipe:0", "-ac", "1", "-codec:a", "libmp3lame", "-b:a", BITRATE,
                        "-metadata", f"title={ep['title']}", "-metadata", "artist=D426 Study Podcast", "-metadata", "album=WGU D426", str(mp3)],
                       input=wav.getvalue(), check=True)
        dur = round(len(pcm) / rate, 2)
        ver = hashlib.sha1(mp3.read_bytes()).hexdigest()[:8]
        manifest["episodes"][ep_id] = {"title": ep["title"], "file": f"audio/{ep_id}.mp3?v={ver}", "dur": dur, "segs": segs}
        print(f"{ep_id:10s} {dur / 60:5.1f} min  {mp3.stat().st_size / 1e6:5.2f} MB  {len(segs)} lines")

    manifest["episodes"] = {k: manifest["episodes"][k] for k in READY if k in manifest["episodes"]}
    manifest_file.write_text("// Generated by tools/podcast.py. Do not edit.\nwindow.D426_PODCAST = " + json.dumps(manifest, ensure_ascii=False) + ";\n", encoding="utf-8")
    print("wrote", manifest_file.relative_to(ROOT))


if __name__ == "__main__":
    main()
