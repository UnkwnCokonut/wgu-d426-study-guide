"""Rebuild everything generated from data/cards.json.

Run from the repo root:  python3 tools/build.py

Writes:
  data/cards.js                     -> loaded by index.html (works offline, no server needed)
  flashcards/quizlet-import.txt     -> paste into Quizlet's "Import" box (tab between term and definition)
  flashcards/anki-import.csv        -> File > Import in Anki (Front, Back, Tags)
  flashcards/practice-questions.csv -> the multiple-choice bank as a spreadsheet
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "data" / "cards.json").read_text(encoding="utf-8"))
topic_names = {t["id"]: t["name"] for t in data["topics"]}

# 1. JS bundle for the web app
(ROOT / "data" / "cards.js").write_text(
    "// Generated by tools/build.py from data/cards.json. Edit the JSON, not this file.\n"
    "window.D426 = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n",
    encoding="utf-8",
)

# 2. Quizlet import: term<TAB>definition, one card per line
lines = [f'{c["t"]}\t{c["d"]}' for c in data["terms"]]
(ROOT / "flashcards" / "quizlet-import.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")

# 3. Anki import: Front, Back, Tags
with open(ROOT / "flashcards" / "anki-import.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f)
    for c in data["terms"]:
        tag = "D426::" + topic_names[c["topic"]].replace(" & ", "_").replace(" ", "_")
        w.writerow([c["t"], c["d"], tag])

# 4. Practice questions as a spreadsheet
with open(ROOT / "flashcards" / "practice-questions.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f)
    w.writerow(["Topic", "Question", "A", "B", "C", "D", "Answer", "Why"])
    for q in data["questions"]:
        opts = (q["o"] + ["", "", "", ""])[:4]
        w.writerow([topic_names[q["topic"]], q["q"], *opts, "ABCD"[q["a"]], q["e"]])

print(f'{len(data["terms"])} terms, {len(data["questions"])} questions -> built')
