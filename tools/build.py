"""Rebuild everything generated from data/cards.json.

Run from the repo root:  python3 tools/build.py

Writes:
  data/cards.js                     -> loaded by index.html (works offline, no server needed)
  flashcards/quizlet-import.txt     -> paste into Quizlet's "Import" box (tab between term and definition)
  flashcards/anki-import.csv        -> File > Import in Anki (Front, Back, Tags)
  flashcards/practice-questions.csv -> the multiple-choice bank as a spreadsheet
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "data" / "cards.json").read_text(encoding="utf-8"))
topic_names = {t["id"]: t["name"] for t in data["topics"]}

# 1. JS bundle for the web app
(ROOT / "data" / "cards.js").write_text(
    "// Generated by tools/build.py from data/cards.json. Edit the JSON, not this file.\n"
    "window.D426 = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n",
    encoding="utf-8",
)

# 2. Quizlet import: term<TAB>definition, one card per line
lines = [f'{c["t"]}\t{c["d"]}' for c in data["terms"]]
(ROOT / "flashcards" / "quizlet-import.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")

# 3. Anki import: Front, Back, Tags
with open(ROOT / "flashcards" / "anki-import.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f)
    for c in data["terms"]:
        tag = "D426::" + topic_names[c["topic"]].replace(" & ", "_").replace(" ", "_")
        w.writerow([c["t"], c["d"], tag])

# 4. Practice questions as a spreadsheet
with open(ROOT / "flashcards" / "practice-questions.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f)
    w.writerow(["Topic", "Question", "A", "B", "C", "D", "Answer", "Why"])
    for q in data["questions"]:
        opts = (q["o"] + ["", "", "", ""])[:4]
        w.writerow([topic_names[q["topic"]], q["q"], *opts, "ABCD"[q["a"]], q["e"]])

# 5. Guide modules -> pre-rendered HTML for the website's Guide tab (needs: pip install markdown)
import html as _html
import re

import markdown

MODULE_TOPIC = {1: "basics", 2: "relational", 3: "sql", 4: "statements", 5: "keys",
                6: "queries", 7: "joins", 8: "design", 9: "logical", 10: "physical"}
MD = lambda s: markdown.markdown(s, extensions=["tables", "fenced_code"])


def render_module(text):
    lines = text.splitlines()
    title = time = ""
    body, slots, i = [], {}, 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("# ") and not title:
            title = re.sub(r"^#\s*\d+\.\s*", "", ln).strip()
        elif ln.startswith("**Time:**"):
            time = ln.replace("**Time:**", "").strip()
        elif ln.startswith("[← "):
            pass  # the site has its own prev/next buttons
        elif ln.startswith("> [!"):  # GitHub alert -> callout
            kind = re.match(r"> \[!(\w+)\]", ln).group(1).lower()
            inner = []
            i += 1
            while i < len(lines) and lines[i].startswith(">"):
                inner.append(lines[i][1:].lstrip(" ") if lines[i] != ">" else "")
                i += 1
            fixed = []
            for x in inner:  # Python-Markdown needs a blank line before a list
                if x.startswith("- ") and fixed and not fixed[-1].startswith("- ") and fixed[-1] != "":
                    fixed.append("")
                fixed.append(x)
            key = f"SLOT{len(slots)}X"
            slots[key] = f'<div class="callout {kind}">{MD(chr(10).join(fixed))}</div>'
            body += ["", key, ""]
            continue
        elif ln.startswith("<details><summary>"):  # self-check question
            q = re.match(r"<details><summary>(.*)</summary>", ln).group(1)
            ans = []
            i += 1
            while i < len(lines) and not lines[i].startswith("</details>"):
                ans.append(lines[i])
                i += 1
            key = f"SLOT{len(slots)}X"
            slots[key] = f'<details class="check"><summary>{_html.escape(q, quote=False)}</summary><div class="ans">{MD(chr(10).join(ans))}</div></details>'
            body += ["", key, ""]
        else:
            body.append(re.sub(r"^  (\d+\.|-) ", r"    \1 ", ln))  # 2-space nested lists -> 4
        i += 1
    out = MD("\n".join(body))
    for key, frag in slots.items():
        out = out.replace(f"<p>{key}</p>", frag)
    out = re.sub(r'href="00-cram-sheet\.md"', 'href="#cram"', out)
    out = re.sub(r'href="(\d\d-[\w-]+)\.md"', r'href="#guide/\1"', out)
    out = out.replace('href="README.md"', 'href="#guide"')
    return title, time, out


guide = []
for path in sorted((ROOT / "guide").glob("[0-9][0-9]-*.md")):
    n = int(path.name[:2])
    if n == 0:
        continue  # the cram sheet is its own tab, built from cards.json
    title, time, body = render_module(path.read_text(encoding="utf-8"))
    guide.append({"id": path.stem, "n": n, "title": title, "time": time, "topic": MODULE_TOPIC[n], "html": body})
(ROOT / "data" / "guide.js").write_text(
    "// Generated by tools/build.py from guide/*.md. Edit the Markdown, not this file.\n"
    "window.D426_GUIDE = " + json.dumps(guide, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)

print(f'{len(data["terms"])} terms, {len(data["questions"])} questions, {len(guide)} guide modules -> built')
